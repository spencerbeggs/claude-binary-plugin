/**
 * Proxy script template for cross-platform plugin distribution.
 *
 * @remarks
 * Generates a thin shell proxy script that wraps SessionStart hooks.
 * The proxy checks if the plugin binary exists and performs just-in-time
 * compilation on the target machine if needed.
 *
 * **Fast path**: Binary exists + node_modules present -> exec to binary (zero overhead)
 * **Slow path**: Buffer stdin -> acquire lock -> bun install -> build -> forward stdin
 * **Error path**: Emit `{}` to stdout (valid passthrough JSON) + error to stderr + exit 0
 *
 * @see {@link GenerateProxyScriptOptions}
 */

/**
 * Options for generating a proxy script.
 * @public
 */
export interface GenerateProxyScriptOptions {
	/** Binary filename (e.g., "workflow.plugin") */
	binaryName: string;
	/** Plugin config file relative to plugin root (default: "plugin.config.ts") */
	configFile?: string;
	/** Plugin name for log messages */
	pluginName?: string;
}

/**
 * Generates a bash proxy script for just-in-time plugin compilation.
 *
 * The proxy script is designed to wrap SessionStart hooks. It checks if the
 * plugin binary exists and performs on-demand compilation if needed. All
 * non-SessionStart hooks point directly at the binary, relying on the
 * guarantee that SessionStart fires before any other hook type.
 *
 * @param options - Generation options
 * @returns Bash script string
 *
 * @example
 * ```typescript
 * const script = generateProxyScript({
 *   binaryName: "workflow.plugin",
 *   configFile: "plugin.config.ts",
 *   pluginName: "workflow",
 * });
 *
 * await Bun.write("scripts/setup-proxy.sh", script);
 * ```
 *
 * @public
 */
export function generateProxyScript(options: GenerateProxyScriptOptions): string {
	const { binaryName, configFile = "plugin.config.ts", pluginName = binaryName.replace(/\.plugin$/, "") } = options;

	return `#!/usr/bin/env bash
# =============================================================================
# ${pluginName} - Setup Proxy Script
# =============================================================================
#
# Auto-generated by claude-binary-plugin prepare.
# This script wraps SessionStart hooks to provide just-in-time compilation.
#
# Fast path: binary exists + node_modules present -> exec to binary
# Slow path: buffer stdin -> lock -> bun install -> build -> forward stdin
# Error path: emit {} to stdout (valid passthrough) + error to stderr + exit 0
#
# DO NOT EDIT - regenerate with: claude-binary-plugin prepare
# =============================================================================

set -euo pipefail

BINARY_NAME="${binaryName}"
CONFIG_FILE="${configFile}"
PLUGIN_NAME="${pluginName}"

# Resolve plugin root from this script's location
SCRIPT_DIR="$(cd "$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
PLUGIN_DIR="$(cd "\${SCRIPT_DIR}/.." && pwd)"
BINARY_PATH="\${PLUGIN_DIR}/\${BINARY_NAME}"

# Override CLAUDE_PLUGIN_ROOT if not set (for manual testing)
CLAUDE_PLUGIN_ROOT="\${CLAUDE_PLUGIN_ROOT:-\${PLUGIN_DIR}}"

# Lock configuration
LOCK_DIR="\${PLUGIN_DIR}/.build-lock"
LOCK_STALE_SECONDS=300

# -----------------------------------------------------------------------------
# Portable stat: get file modification time in epoch seconds
# -----------------------------------------------------------------------------
get_mtime() {
    local target="$1"
    # macOS stat
    if stat -f %m "\${target}" 2>/dev/null; then
        return
    fi
    # GNU/Linux stat
    stat -c %Y "\${target}" 2>/dev/null
}

# -----------------------------------------------------------------------------
# Error handler: emit valid passthrough JSON and exit cleanly
# -----------------------------------------------------------------------------
emit_error() {
    local msg="$1"
    echo '{}' >&1
    echo "[\${PLUGIN_NAME}] ERROR: \${msg}" >&2
    exit 0
}

# -----------------------------------------------------------------------------
# Lock acquisition (mkdir-based, portable)
# -----------------------------------------------------------------------------
acquire_lock() {
    # Check for stale lock
    if [ -d "\${LOCK_DIR}" ]; then
        local lock_mtime
        lock_mtime="$(get_mtime "\${LOCK_DIR}" 2>/dev/null || echo 0)"
        local now
        now="$(date +%s)"
        local age=$(( now - lock_mtime ))
        if [ "\${age}" -gt "\${LOCK_STALE_SECONDS}" ]; then
            rmdir "\${LOCK_DIR}" 2>/dev/null || true
        fi
    fi

    # Try to acquire
    if ! mkdir "\${LOCK_DIR}" 2>/dev/null; then
        # Another process holds the lock - wait for it
        local waited=0
        while [ -d "\${LOCK_DIR}" ] && [ "\${waited}" -lt "\${LOCK_STALE_SECONDS}" ]; do
            sleep 1
            waited=$(( waited + 1 ))
        done

        # Re-check: binary might have been built by the other process
        if [ -x "\${BINARY_PATH}" ]; then
            return 1  # Signal: skip build, binary is ready
        fi

        # Try again
        if ! mkdir "\${LOCK_DIR}" 2>/dev/null; then
            emit_error "Could not acquire build lock after \${waited}s"
        fi
    fi

    # Clean up lock on exit
    trap 'rmdir "\${LOCK_DIR}" 2>/dev/null || true' EXIT
    return 0
}

# -----------------------------------------------------------------------------
# Build the plugin binary
# -----------------------------------------------------------------------------
build_plugin() {
    echo "[\${PLUGIN_NAME}] Installing dependencies..." >&2
    if ! (cd "\${PLUGIN_DIR}" && bun install --frozen-lockfile 2>&1) >&2; then
        emit_error "bun install failed"
    fi

    echo "[\${PLUGIN_NAME}] Building plugin binary..." >&2
    if ! (cd "\${PLUGIN_DIR}" && bun x claude-binary-plugin build "\${CONFIG_FILE}" --no-persist 2>&1) >&2; then
        emit_error "Plugin build failed"
    fi

    if [ ! -x "\${BINARY_PATH}" ]; then
        # Try chmod in case build produced a non-executable file
        chmod +x "\${BINARY_PATH}" 2>/dev/null || true
        if [ ! -x "\${BINARY_PATH}" ]; then
            emit_error "Build completed but binary not found at \${BINARY_PATH}"
        fi
    fi
}

# =============================================================================
# Main
# =============================================================================

# Fast path: binary exists and node_modules present -> exec directly
if [ -x "\${BINARY_PATH}" ] && [ -d "\${PLUGIN_DIR}/node_modules" ]; then
    exec "\${BINARY_PATH}" "$@"
fi

# Slow path: need to build
# Buffer stdin so we can forward it after building
STDIN_BUFFER="$(cat)"

# Acquire build lock (returns 1 if another process already built it)
if acquire_lock; then
    # Double-check after acquiring lock
    if [ ! -x "\${BINARY_PATH}" ] || [ ! -d "\${PLUGIN_DIR}/node_modules" ]; then
        build_plugin
    fi
fi

# Forward buffered stdin to the binary
echo "\${STDIN_BUFFER}" | exec "\${BINARY_PATH}" "$@"
`;
}
